def save_to_txt(names, filename="chinese_names_30k.txt"):
    try:
        with open(filename, 'w', encoding='utf-8') as f:
            for name in names:
                f.write(name + '\n')
        print(f"💾 文件已保存：{filename}")
        print(f"   位置：当前运行目录")
    except Exception as e:
        print(f"❌ 保存文件时出错：{e}")

