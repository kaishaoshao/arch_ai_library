    while len(generated_names) < count and attempts < max_attempts:
        attempts += 1

        # 随机选姓
        surname = random.choice(surnames)

        # 随机决定名字长度 (1个字 或 2个字)，双字名概率更高
        name_length = random.choice([1, 2, 2, 2])

        if name_length == 1:
            # 单字名
            name_part = random.choice(all_name_chars)
            full_name = surname + name_part
        else:
            # 双字名
            char1 = random.choice(all_name_chars)
            char2 = random.choice(all_name_chars)
